        <section>
            <h2>1. Data yang kami kumpulkan</h2>
            <ul>
                <li><strong>Donatur:</strong> nama, email atau nomor WhatsApp, nominal, metode dan waktu pembayaran, status donasi, dan pilihan menyamarkan nama.</li>
                <li><strong>Pengaju program:</strong> nama, kontak, cerita program, target, data rekening penerima, dan foto yang Anda unggah.</li>
                <li><strong>Staf:</strong> nama, email, peran, serta catatan login berupa waktu, alamat IP, dan jenis perangkat.</li>
                <li><strong>Tiket bantuan:</strong> nama, email, isi pesan, dan kode donasi atau pengajuan yang Anda sebutkan.</li>
                <li><strong>Teknis:</strong> cookie sesi yang diperlukan agar halaman berfungsi.</li>
            </ul>
            <p>Kami tidak meminta dan tidak menyimpan nomor kartu atau data login bank Anda.</p>
        </section>

        <section>
            <h2>2. Untuk apa data dipakai</h2>
            <ul>
                <li>Memproses donasi dan menerbitkan serta mengirim kuitansi.</li>
                <li>Memeriksa dan menayangkan pengajuan program, lalu menghubungi pengaju.</li>
                <li>Pembukuan, audit, dan mendeteksi penyalahgunaan, termasuk percobaan login yang mencurigakan.</li>
            </ul>
            <p>Kami tidak menjual data Anda dan tidak memakainya untuk iklan.</p>
        </section>

        <section>
            <h2>3. Siapa yang bisa melihat data Anda</h2>
            <ul>
                <li><strong>Publik</strong> hanya melihat nama donatur (atau Hamba Allah jika Anda menyamarkannya), nominal, dan waktu donasi pada halaman program. Kontak Anda tidak pernah ditampilkan.</li>
                <li><strong>Staf</strong> (bendahara, admin, auditor, super admin) melihat data sesuai tugasnya untuk pembukuan dan audit.</li>
                <li><strong>Penyedia pembayaran</strong> akan menerima data yang diperlukan untuk memproses pembayaran begitu pembayaran sungguhan diaktifkan. Saat ini pembayaran masih simulasi.</li>
            </ul>
        </section>

        <section>
            <h2>4. Layanan pihak ketiga</h2>
            <p>Huruf di situs ini dimuat dari Google Fonts, sehingga peramban Anda terhubung ke server Google saat halaman dibuka. Di luar itu, situs tidak memuat pelacak atau skrip iklan.</p>
        </section>

        <section>
            <h2>5. Berapa lama data disimpan</h2>
            <p>Data donasi, penyaluran, dan log aktivitas disimpan selama diperlukan untuk pembukuan dan audit. Log aktivitas sengaja dibuat berantai agar tidak bisa diubah diam-diam, sehingga catatannya tidak dihapus.</p>
        </section>

        <section>
            <h2>6. Hak Anda</h2>
            <p>Anda dapat meminta akses terhadap data pribadi Anda, meminta koreksi bila ada yang keliru, dan meminta penghapusan atau penyamaran sejauh tidak bertentangan dengan kewajiban pembukuan dan audit. Ini sejalan dengan Undang-Undang Pelindungan Data Pribadi (UU No. 27 Tahun 2022). Sampaikan permintaan kepada pengelola SIDONA dengan menyebut kode kuitansi atau kode pengajuan Anda.</p>
        </section>

        <section>
            <h2>7. Keamanan</h2>
            <p>Akses staf memerlukan akun dan peran, kata sandi disimpan dalam bentuk ter-hash, dan setiap perubahan penting dicatat di log audit. Tidak ada sistem yang bebas risiko, tetapi kami berupaya menjaga data Anda sebaik mungkin.</p>
        </section>

        <section>
            <h2>8. Anak-anak</h2>
            <p>Layanan ini ditujukan bagi pengguna dewasa. Donatur di bawah umur sebaiknya berdonasi bersama orang tua atau wali.</p>
        </section>

        <section>
            <h2>9. Perubahan kebijakan</h2>
