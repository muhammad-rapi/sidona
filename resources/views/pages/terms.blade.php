    <div class="legal-prose space-y-9">
        <section>
            <h2>1. Persetujuan</h2>
            <p>Dengan membuka atau memakai SIDONA, Anda menyetujui syarat ini. Kalau tidak setuju, mohon tidak memakai layanan.</p>
        </section>

        <section>
            <h2>2. Tentang layanan</h2>
            <p>SIDONA adalah sistem informasi donasi dan audit. Kami mempertemukan donatur dengan program sosial, mencatat setiap donasi, dan mencatat penyaluran dana secara terbuka bagi auditor.</p>
            <p>Saat ini pembayaran masih berjalan dalam mode simulasi. Selama mode itu aktif, tidak ada uang yang berpindah. Kami akan menandainya dengan jelas di halaman pembayaran.</p>
        </section>

        <section>
            <h2>3. Donasi</h2>
            <ul>
                <li>Donasi bersifat sukarela. Nominal minimal Rp 10.000 dan maksimal Rp 1.000.000.000 per transaksi.</li>
                <li>Donasi dianggap berhasil otomatis saat pembayaran terkonfirmasi. Tidak ada persetujuan manual oleh admin.</li>
                <li>Donasi yang sudah berhasil tidak dapat dibatalkan lewat situs. Kesalahan transfer dapat disampaikan kepada pengelola dengan menyebut kode kuitansi.</li>
                <li>Data yang Anda isi harus benar, terutama kontak untuk kuitansi.</li>
            </ul>
        </section>

        <section>
            <h2>4. Pengajuan program</h2>
            <ul>
                <li>Anda bertanggung jawab atas kebenaran cerita, target, dan rekening penerima yang Anda isi.</li>
                <li>Rekening harus milik Anda atau pihak yang Anda wakili secara sah.</li>
                <li>Admin berhak menolak pengajuan, dan wajib memberikan alasannya. Pengajuan yang disetujui tayang di situs dan menerima donasi sampai masa programnya habis.</li>
                <li>Dilarang mengajukan program yang menipu, menyesatkan, melanggar hukum, atau tidak bertujuan sosial.</li>
                <li>Kami dapat menghentikan program yang kemudian terbukti melanggar syarat ini.</li>
            </ul>
        </section>

        <section>
            <h2>5. Penyaluran dana</h2>
            <p>Dana program disalurkan lewat pengajuan bendahara dan persetujuan admin yang berbeda. Jumlah penyaluran tidak boleh melebihi saldo program. Setiap pengajuan dan keputusan tercatat dan dapat diperiksa auditor.</p>
        </section>

        <section>
            <h2>6. Hal yang dilarang</h2>
            <ul>
                <li>Mencoba mengakses area staf, data orang lain, atau merusak, membebani, dan mengelabui sistem.</li>
                <li>Membuat donasi atau pengajuan palsu atau berulang untuk tujuan menyerang atau menyalahgunakan layanan.</li>
                <li>Memakai layanan untuk pencucian uang atau tindak pidana lain.</li>
            </ul>
        </section>

        <section>
            <h2>7. Konten dan foto</h2>
            <p>Foto dan teks yang Anda unggah untuk sebuah program harus milik Anda atau Anda berhak memakainya. Dengan mengunggah, Anda mengizinkan SIDONA menampilkannya di halaman program tersebut.</p>
        </section>

        <section>
            <h2>8. Batasan tanggung jawab</h2>
            <p>Kami berupaya menjaga layanan tetap tersedia dan akurat, tetapi tidak menjamin layanan selalu bebas gangguan. Isi dan klaim setiap program menjadi tanggung jawab pengajuannya; kami memeriksa kelengkapannya, tetapi tidak dapat menjamin hasil yang dijanjikan program.</p>
        </section>

        <section>
            <h2>9. Perubahan syarat</h2>
            <p>Syarat ini dapat berubah. Versi terbaru selalu ada di halaman ini beserta tanggal pembaruannya. Memakai layanan setelah perubahan berarti Anda menerima versi barunya.</p>
        </section>

        <section>
            <h2>10. Hukum yang berlaku</h2>
            <p>Syarat ini tunduk pada hukum Republik Indonesia.</p>
        </section>
